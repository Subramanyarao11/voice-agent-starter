export function normalizeUiLocale(value: string | null | undefined): UiLocale {
  const normalized = (value ?? "en").trim().toLowerCase().split("-")[0];
  return UI_LOCALES.includes(normalized as UiLocale) ? (normalized as UiLocale) : "en";
}

export function createUiTranslator(locale: string | null | undefined): {
  locale: UiLocale;
  reviewStatus: UiBundleReviewStatus;
  t: UiTranslator;
} {
  const normalized = normalizeUiLocale(locale);
  const copy = { ...ENGLISH_COPY, ...(DRAFT_COPY[normalized] ?? {}) };
  return {
    locale: normalized,
    reviewStatus: UI_BUNDLE_REVIEW_STATUS[normalized],
    t: (key, variables) => {
      const template = copy[key] ?? ENGLISH_COPY[key];
      return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, variable: string) =>
        String(variables?.[variable] ?? `{${variable}}`),
      );
    },
  };
}

export function localeHtml(lang: string | null | undefined): string {
  const normalized = normalizeUiLocale(lang);
  return normalized === "en" ? "en-IN" : `${normalized}-IN`;
}
